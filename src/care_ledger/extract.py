log = logging.getLogger(__name__)

SYSTEM_PROMPT = """\
You convert one clinical document into typed claims. Record only what this document states. \
Never reconcile with other documents, fill gaps, or infer facts.

Evidence: every claim lists one or more quotes copied verbatim from the document: exact characters \
including spacing, dashes, and punctuation, with no added quotation marks, ellipses, or rewording. Each \
quote must occur exactly once in the document; extend it with neighbouring text when needed to make it unique.

Encounters: emit one section per encounter per document section. Use the source encounter identifier, \
or the appointment identifier when no encounter identifier exists. source_status is "draft" for draft, \
unsigned, autogenerated, or template text, otherwise "final". authored_on is the date the section's \
statements were originally made or signed, never the date a copy was received, resent, imported, or exported.
- attendance: whether the patient was present. A completed appointment that the patient did not attend \
(for example a partner-only collateral contact or professional-only coordination) is patient_absent. \
Use null when the section does not state attendance.
- patient_presence: only intervals when the patient was actually in contact: actual arrival to departure, \
stated patient contact, or connected video intervals. Never use scheduled times, clinician-only or \
therapist session intervals, or portions when the patient was absent. Use several intervals when contact \
was interrupted.
- breaks: nontherapeutic intervals (breaks, disconnections) the document states for the encounter.
- charges: billing charges recorded for the encounter.

Corrections: only when the document explicitly corrects a previously recorded patient arrival \
(presence_start) or departure (presence_end) time, with the replaced and replacement times.

Assessments: standardized questionnaire results with the patient's completion date (not the import, \
receipt, or review date), total score, and source form identifier when stated. Include imported or \
repeated results as they appear.

Observations: patient-reported, clinician-assessed, or collateral-reported statements about symptoms, \
functioning, safety, the reason a visit occurred, or overall clinical assessment. statement is a brief, \
faithful paraphrase. Link encounter_id when the observation was made during an encounter.

Plans: treatment-plan participation requirements with effective dates, weekly minimum therapy days and \
minutes, and the service types that count toward them.

Times: each start or end is a single local clock time as HH:MM (example: 10:45). Do not write a range, \
Z, or UTC offset in a time field.

Use empty lists when the document contains no claims of a type.
"""

PRICING_PER_MILLION = {"gpt-5.4-mini": {"input": 0.75, "cached_input": 0.075, "output": 4.50}}


def estimate_cost(model: str, input_tokens, cached_input_tokens, output_tokens) -> float | None:
    price = PRICING_PER_MILLION.get(model)
    if price is None or input_tokens is None or output_tokens is None:
        return None
    cached = cached_input_tokens or 0
    return ((input_tokens - cached) * price["input"] + cached * price["cached_input"]
            + output_tokens * price["output"]) / 1_000_000


MAX_ATTEMPTS = 2


@dataclass(slots=True)
class CallResult:
    document_id: int
    started_at: str
    elapsed_ms: float
    envelope: ExtractionEnvelope | None
    error: str | None
    request_id: str | None
    usage: dict
    output_text: str | None = None
    evidence_rejected: bool = False


def _call_model(client: OpenAI, settings: Settings, document_id: int, content: str, messages: list[dict]) -> CallResult:
    started_at = datetime.now(timezone.utc).isoformat()
    started = time.perf_counter()
    result = CallResult(document_id, started_at, 0.0, None, None, None, {})
    try:
        response = client.responses.parse(
            model=settings.model,
            reasoning={"effort": settings.reasoning_effort},
            input=messages,
            text_format=ExtractionEnvelope,
            store=False,
        )
        result.request_id = getattr(response, "_request_id", None)
        result.output_text = response.output_text
        if response.usage:
            result.usage = {
                "input_tokens": response.usage.input_tokens,
                "cached_input_tokens": response.usage.input_tokens_details.cached_tokens,
                "output_tokens": response.usage.output_tokens,
                "reasoning_tokens": response.usage.output_tokens_details.reasoning_tokens,
            }
        if response.output_parsed is None:
            raise ValueError("model returned no structured output")
        validate_evidence(content, response.output_parsed)
        result.envelope = response.output_parsed
    except EvidenceError as exc:
        result.error = f"EvidenceError: {exc}"
        result.evidence_rejected = True
    except Exception as exc:  # recorded per document; the batch reports all failures
        result.error = f"{type(exc).__name__}: {exc}"
    result.elapsed_ms = (time.perf_counter() - started) * 1000
    return result


def _extract_document(client: OpenAI, settings: Settings, document_id: int, content: str) -> list[CallResult]:
    """Extract one document, giving the model one chance to repair quotes that fail evidence validation."""
    messages = [{"role": "system", "content": SYSTEM_PROMPT}, {"role": "user", "content": content}]
    attempts = []
    for _ in range(MAX_ATTEMPTS):
        result = _call_model(client, settings, document_id, content, messages)
        attempts.append(result)
        if not result.evidence_rejected:
            break
        messages = [*messages,
                    {"role": "assistant", "content": result.output_text},
                    {"role": "user", "content": f"These evidence quotes failed validation: {result.error}. "
                                                "Return the complete extraction again with every quote copied "
                                                "verbatim and occurring exactly once in the document."}]
    return attempts


def _record(db: sqlite3.Connection, settings: Settings, result: CallResult) -> int:
    return db.execute(
        "INSERT INTO model_calls(document_id, extraction_version, model, reasoning_effort, started_at, elapsed_ms, "
        "status, error, request_id, input_tokens, cached_input_tokens, output_tokens, reasoning_tokens) "
        "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
        (result.document_id, settings.extraction_version, settings.model, settings.reasoning_effort,
         result.started_at, result.elapsed_ms, "failed" if result.error else "succeeded", result.error,
         result.request_id, result.usage.get("input_tokens"), result.usage.get("cached_input_tokens"),
         result.usage.get("output_tokens"), result.usage.get("reasoning_tokens")),
    ).lastrowid


@dataclass(frozen=True, slots=True)
class ExtractSummary:
    pending: int
    succeeded: int
    failed: dict[int, str]
    elapsed_s: float


def extract_pending(db: sqlite3.Connection, settings: Settings, workers: int) -> ExtractSummary:
    pending = db.execute(
        "SELECT id, content FROM documents d WHERE NOT EXISTS "
        "(SELECT 1 FROM extractions x WHERE x.document_id = d.id AND x.version = ?) ORDER BY id",
        (settings.extraction_version,),
    ).fetchall()
    started = time.perf_counter()
    failed: dict[int, str] = {}
    succeeded = 0
    if pending:
        client = OpenAI(timeout=180.0, max_retries=2)
        with ThreadPoolExecutor(max_workers=workers) as pool:
            futures = [pool.submit(_extract_document, client, settings, d["id"], d["content"]) for d in pending]
            for future in as_completed(futures):
                *retried, result = future.result()
                with db:
                    for attempt in retried:
                        _record(db, settings, attempt)
                try:
                    with db:
                        call_id = _record(db, settings, result)
                        if result.envelope is not None:
                            try:
                                persist_extraction(db, result.document_id, result.envelope,
                                                   version=settings.extraction_version,
                                                   producer=settings.model, model_call_id=call_id)
                            except AlreadyExtracted:
                                pass
                except (ValueError, sqlite3.IntegrityError) as exc:
                    result.error = f"{type(exc).__name__}: {exc}"
                    with db:
                        _record(db, settings, result)
                if result.error:
                    failed[result.document_id] = result.error
                    log.error("document %s extraction failed: %s", result.document_id, result.error)
                else:
                    succeeded += 1
                    log.info("document %s extracted in %.1fs", result.document_id, result.elapsed_ms / 1000)
    return ExtractSummary(len(pending), succeeded, failed, time.perf_counter() - started)
